#!/usr/bin/env node
// Web oracle goldens for native/meta (Rewards + Progress.record_result).
//   node native/meta/tools/gen_rewards_golden.mjs          # rewrite rewards_golden.json next to this file
//   node native/meta/tools/gen_rewards_golden.mjs --check  # exit 1 if the file differs
// Runs the frozen web game/js/rewards.js (computeReward, applyReward, won, shortNum) unmodified, composed the way
// main.js:showResult (549-571) and retryFromDiscovery (697) compose it. One progress object is carried through all
// cases, so album count / best stars / unlock / milestone carry-over are part of the golden.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeReward, applyReward, won, shortNum } from '../../../game/js/rewards.js';
import { TUNE, SHOP_DEFAULT } from '../../../game/js/config.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../../..');
const STAGES = JSON.parse(readFileSync(resolve(ROOT, 'native/data/stages.json'), 'utf8')).stages;
const OUT = resolve(HERE, 'rewards_golden.json');

// Inputs mirror the stage_finished result dict (docs/NATIVE_PARITY.md 7 G1). hp_end/minis drive missions (main.js:559).
const CASES = [
  { stage: 1, hp_end: 80, minis_done: 2, minis_total: 2, cath: 88, freed: 1200, cheaters: 1, mini_fines: 100000, has4k: false, fails: 0, seed: 1, score: 30000 },
  { stage: 1, hp_end: 40, minis_done: 2, minis_total: 2, cath: 64, freed: 1180, cheaters: 0, mini_fines: 50000, has4k: true, fails: 1, seed: 997, score: 25000 },
  { stage: 3, hp_end: 50, minis_done: 1, minis_total: 3, cath: 40, freed: 3000, cheaters: 2, mini_fines: 0, has4k: true, fails: 2, seed: 500, score: 12000 },
  { stage: 18, hp_end: 100, minis_done: 4, minis_total: 4, cath: 100, freed: 30000, cheaters: 3, mini_fines: 160000, has4k: true, fails: 3, seed: 123, score: 99000 },
  { stage: 31, hp_end: 60, minis_done: 0, minis_total: 2, cath: 12, freed: 0, cheaters: 0, mini_fines: 0, has4k: false, fails: 0, seed: 2, score: 400 },
  { stage: 11, hp_end: 61, minis_done: 3, minis_total: 3, cath: 77, freed: 4321, cheaters: 1, mini_fines: 110000, has4k: false, fails: 1, seed: 640, score: 41000 },
  { stage: 100, hp_end: 99, minis_done: 4, minis_total: 4, cath: 95, freed: 52000, cheaters: 0, mini_fines: 200000, has4k: true, fails: 0, seed: 77, score: 150000 },
];

const AT0 = 1760000000000;
const realNow = Date.now;
const progress = { ver: 3, unlocked: 1, stars: {}, best: {}, wallet: 0, subs: 0, album: {}, owned: [], equip: { ...SHOP_DEFAULT } };
const out = [];
CASES.forEach((c, i) => {
  const idx = STAGES.findIndex((s) => s.id === c.stage);
  const stage = STAGES[idx];
  const missions = [true, c.hp_end >= 60, c.minis_done >= c.minis_total];               // main.js:559
  const stars = missions.filter(Boolean).length;                                       // main.js:560
  const payRetryMul = c.fails ? Math.max(TUNE.hp.retryPayMin, 1 - TUNE.hp.retryPayStep * c.fails) : 1; // main.js:395,697
  const payMult = (c.has4k ? 1.25 : 1) * (payRetryMul || 1);                            // main.js:567
  const reward = computeReward(stage, { stars, cath: c.cath, freed: c.freed, bumps: 0, cheaters: c.cheaters, miniFines: c.mini_fines, payMult }, c.seed);
  const photo = `user://album/${c.stage}.jpg`;
  Date.now = () => AT0 + i;
  const { milestone } = applyReward(progress, stage, reward, photo);
  Date.now = realNow;
  progress.unlocked = Math.min(STAGES.length, Math.max(progress.unlocked, idx + 2));   // main.js:569
  progress.stars[stage.id] = Math.max(progress.stars[stage.id] || 0, stars);           // main.js:570
  progress.best[stage.id] = Math.max(progress.best[stage.id] || 0, c.score);           // main.js:571
  out.push({ in: c, at: AT0 + i, missions, stars, payMult, reward, milestone, progress: JSON.parse(JSON.stringify(progress)) });
});

const NUMS = [0, 7, 999, 1000, 9999, 10000, 10500, 11500, 12350, 12500, 15000, 17500, 99949, 99950, 99999, 100000, 105000, 115000, 125000, 1234567, 1005000, 50000000];
const doc = {
  _doc: 'generated by native/meta/tools/gen_rewards_golden.mjs from game/js/rewards.js + main.js:showResult composition — do not edit',
  tune_hp: { retryPayStep: TUNE.hp.retryPayStep, retryPayMin: TUNE.hp.retryPayMin },
  at0: AT0,
  cases: out,
  format: NUMS.map((n) => ({ n, won: won(n), short: shortNum(n) })),
};
const text = JSON.stringify(doc, null, 1) + '\n';
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('rewards_golden.json is stale'); process.exit(1); }
  console.log('rewards_golden.json up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${out.length} cases)`);
}
