// Generates native/screens/svg_art.gd from the frozen web UI (game/js/ui.js): icon SVGs, shop item art,
// road-rule tiles (shoulder / honk modes), special-sign glyphs, dashArt template. Run from the repo root:
//   node native/screens/dev/extract_svg.mjs
// ui.js has no imports and builds its DOM lazily, so it evaluates in Node once the private tables are exported.
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = new URL('../../../', import.meta.url);
const src = readFileSync(new URL('game/js/ui.js', root), 'utf8');
const dir = mkdtempSync(join(tmpdir(), 'lane1-svg-'));
const tmp = join(dir, 'ui_export.mjs');
writeFileSync(tmp, src + '\nexport { SVG, ART, ART_CAT, SH_MODES, HONK_MODES, specialSVG, itemArt, dashArt, wreckerArt };\n');
globalThis.matchMedia = () => ({ matches: false, addEventListener() {} });
const m = await import(pathToFileURL(tmp).href);

const stages = JSON.parse(readFileSync(new URL('native/data/stages.json', root), 'utf8')).stages;
const shop = JSON.parse(readFileSync(new URL('native/data/shop.json', root), 'utf8')).items;
const icons = { ...m.SVG };
// star variants (web colours the path through CSS: .ui-star.is-on → #ffd23f, off → #c9d0d8 at .45 opacity)
icons.star_on = m.SVG.star.replace('class="ui-star__p"', 'fill="#ffd23f"');
icons.star_off = m.SVG.star.replace('class="ui-star__p"', 'fill="#c9d0d8" fill-opacity=".55"').replace('stroke="#fff" stroke-opacity=".7"', 'stroke="#fff" stroke-opacity="0"');
icons.thumb = m.SVG.thumb.replace('currentColor', '#7a828c');
icons.wrecker = m.wreckerArt();
const items = {};
for (const it of shop) items[it.id] = m.itemArt(it);
const wrap = (inner) => `<svg viewBox="0 0 40 40" xmlns="http://www.w3.org/2000/svg">${inner}</svg>`;
const road = { sh: {}, hk: {}, sp: {} };
for (const [k, v] of Object.entries(m.SH_MODES)) road.sh[k] = { label: v.label, short: v.short, tone: v.tone, svg: wrap(v.svg) };
for (const [k, v] of Object.entries(m.HONK_MODES)) road.hk[k] = { label: v.label, short: v.short, tone: v.tone, svg: wrap(v.svg) };
for (const sp of ['구조 상황 · 압정 금지', '보스', '엘리트']) road.sp[sp] = wrap(m.specialSVG(sp));
const dash = { photo: m.dashArt('#COLOR#', 'photo', 0), silhouette: m.dashArt('', 'silhouette') };
// dashArt picks the sky from seed % 4; keep the four skies so GDScript can swap them
dash.skies = ['#3d5878', '#5a4a6e', '#5b6f7f', '#141a33'];
const xmlns = (s) => s.replace(/<svg(?![^>]*xmlns)/, '<svg xmlns="http://www.w3.org/2000/svg"').replace(/\s+aria-hidden="true"/g, '').replace(/\s+class="[^"]*"/g, '');
for (const k in icons) icons[k] = xmlns(icons[k]);
for (const k in items) items[k] = xmlns(items[k]);
dash.photo = xmlns(dash.photo);
dash.silhouette = xmlns(dash.silhouette);
const data = { icons, items, road, dash };
const head = '## GENERATED by native/screens/dev/extract_svg.mjs from game/js/ui.js (frozen web oracle) — do not edit.\n'
  + '## SVG strings rasterised at runtime by Kit.svg_tex (Image.load_svg_from_string), so no import step is needed.\n'
  + 'class_name SvgArt\nextends RefCounted\n\n';
const body = Object.entries(data).map(([k, v]) => `const ${k.toUpperCase()}: Dictionary = ${JSON.stringify(v, null, '\t').replace(/\n/g, '\n')}\n`).join('\n');
writeFileSync(new URL('native/screens/svg_art.gd', root), head + body);
console.log('icons', Object.keys(icons).length, 'items', Object.keys(items).length, 'sh', Object.keys(road.sh).length, 'hk', Object.keys(road.hk).length);
